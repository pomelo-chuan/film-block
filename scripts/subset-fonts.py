"""Build Unicode-range WOFF2 slices; keep all original characters and licenses."""
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont
root=Path(__file__).resolve().parents[1]
out=root/'public/fonts/subsets'
out.mkdir(parents=True,exist_ok=True)
css=['/* Generated by scripts/subset-fonts.py; all characters in the source fonts are retained. */']
for slug,family in [('fusion-pixel-12','Fusion Pixel 12')]:
 source=root/f'public/fonts/{slug}.woff2'
 points=set(TTFont(source).getBestCmap())
 common={p for p in points if p<0x250 or 0x2000<=p<=0x27ff}
 groups=[('common',common),('extended',points-common)]
 for name,chars in groups:
  if not chars:continue
  font=TTFont(source);options=subset.Options();options.flavor='woff2'
  worker=subset.Subsetter(options=options);worker.populate(unicodes=chars);worker.subset(font)
  filename=f'{slug}-{name}.woff2';font.save(out/filename)
  unicode='U+0-24F,U+2000-27FF' if name=='common' else 'U+250-1FFF,U+2800-10FFFF'
  css.append(f"@font-face{{font-family:'{family}';font-style:normal;font-weight:400;font-display:swap;src:url('/fonts/subsets/{filename}') format('woff2');unicode-range:{unicode};}}")
for slug,family in [('fusion-pixel-10','Fusion Pixel 10'),('cubic-11','Cubic 11')]:
 css.append(f"@font-face{{font-family:'{family}';font-style:normal;font-weight:400;font-display:swap;src:url('/fonts/{slug}.woff2') format('woff2');}}")
(root/'src/fonts.css').write_text('\n'.join(css)+'\n')
